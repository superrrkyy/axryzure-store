export const PRODUCTS: Product[] = CORE_PRODUCTS.map((p) => ({
  ...p,
  ...(CONTENT[p.slug] ?? {
    description: [],
    features: [],
    included: [],
    compatibility: [],
    formats: [],
    license: '',
    changelog: [],
    faq: [],
  }),
}))

export const getProduct = (slug: string): Product | undefined =>
  PRODUCTS.find((p) => p.slug === slug)

export const getProductById = (id: string): Product | undefined =>
  PRODUCTS.find((p) => p.id === id)

export const discountPct = (p: CoreProduct): number | null =>
  p.originalPrice ? Math.round((1 - p.price / p.originalPrice) * 100) : null

export const FEATURED_PRODUCTS = PRODUCTS.filter((p) => p.featured)
export const TRENDING_PRODUCTS = PRODUCTS.filter((p) => p.trending)
export const NEW_ARRIVALS = PRODUCTS.filter((p) => p.badge === 'new')
export const LIMITED_PRODUCTS = PRODUCTS.filter((p) => p.badge === 'limited')
export const BEST_SELLERS = [...PRODUCTS].sort((a, b) => b.sales - a.sales).slice(0, 5)
export const ON_SALE_PRODUCTS = PRODUCTS.filter((p) => p.originalPrice)

export const relatedProducts = (product: Product, limit = 4): Product[] => {
  const scored = PRODUCTS.filter((p) => p.slug !== product.slug).map((p) => {
    let score = 0
    if (p.category === product.category) score += 4
    if (p.collections.some((c) => product.collections.includes(c))) score += 2
    if (p.type === product.type) score += 1
    if (p.tags.some((t) => product.tags.includes(t))) score += 1
    return { p, score }
  })
  return scored
    .sort((a, b) => b.score - a.score || b.p.sales - a.p.sales)
    .slice(0, limit)
    .map((s) => s.p)
}
